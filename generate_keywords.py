def get_keyword_weight(cat_id, keyword):
    """
    根据分类ID和关键词动态计算权重
    权重优先级：5 > 4 > 3 > 2 > 1
    """
    # 1602 外卖：所有关键词权重最高（5），确保优先匹配
    if cat_id == 1602:
        return 5
    
    # 1601 三餐：菜品关键词权重最低（1），避免误匹配外卖
    if cat_id == 1601:
        if keyword in DISH_KEYWORDS:
            return 1  # 菜品名称权重最低
        else:
            return 3  # 场景词、品牌词默认权重
    
    # 其他分类：默认权重3
    return 3

