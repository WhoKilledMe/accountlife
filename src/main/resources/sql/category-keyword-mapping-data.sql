CREATE TEMPORARY TABLE IF NOT EXISTS tmp_ckm_dedup AS
SELECT 
    MIN(category_id) as category_id,
    keyword,
    MAX(weight) AS weight,
    user_id,
    TRUE AS is_active
FROM category_keyword_mapping
GROUP BY user_id, keyword;

